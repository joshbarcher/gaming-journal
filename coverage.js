/** Express handler serving the self-contained `/coverage/dashboard` page. */
export function createCoverageDashboardRoute(options = {}) {
    const { name = 'app', dataUrl = '/coverage?detail=true' } = options;
    const html = renderDashboardHtml(name, dataUrl);
    return function coverageDashboardHandler(req, res) {
        res.type('html').send(html);
    };
}

/** Fetch/SvelteKit equivalent of createCoverageDashboardRoute. */
export function createCoverageDashboardHandler(options = {}) {
    const { name = 'app', dataUrl = '/coverage?detail=true' } = options;
    const html = renderDashboardHtml(name, dataUrl);
    return function coverageDashboardRequestHandler() {
        return new Response(html, { headers: { 'content-type': 'text/html' } });
    };
}

// ── CLI ──────────────────────────────────────────────────────────────────────
//   node coverage.js --ensure-dir   create ./coverage (node:test won't, and
//                                   `mkdir -p` isn't portable to Windows cmd)
//   node coverage.js --snapshot     write ./.coverage-snapshot.json
//
// Paths are anchored on process.cwd(), so `node ../coverage.js --snapshot` run
// from a sub-package acts on THAT package.

const invokedDirectly = typeof process !== 'undefined'
    && Array.isArray(process.argv)
    && /(^|[\\/])coverage\.js$/.test(process.argv[1] ?? '');

if (invokedDirectly && process.argv.includes('--ensure-dir')) {
    await mkdir(join(process.cwd(), 'coverage'), { recursive: true });
}

if (invokedDirectly && process.argv.includes('--snapshot')) {
    try {
        const result = await writeSnapshot(process.cwd());
        const l = result.totals.lines;
        console.log(
            `coverage: wrote ${SNAPSHOT_FILE} from ${result.source} — `
            + `${l.pct}% lines (${l.covered}/${l.total}) across ${result.fileCount} files`
        );
    } catch (err) {
        console.error(`coverage: ${err.message}`);
        process.exitCode = 1;
    }
}
