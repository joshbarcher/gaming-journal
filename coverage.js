const DASHBOARD_SCRIPT = `
var COV_DATA_URL = '__DATA_URL__';

function covCls(p) { return p >= 80 ? 'good' : p >= 60 ? 'warn' : 'bad'; }
function covEl(tag, cls, text) {
  var el = document.createElement(tag);
  if (cls) el.className = cls;
  if (text !== undefined) el.textContent = text;
  return el;
}
function covNum(n) { return Number(n).toLocaleString('en-US'); }

function covRenderKpis(totals) {
  var wrap = document.getElementById('cov-kpis');
  wrap.innerHTML = '';
  ['lines', 'statements', 'functions', 'branches'].forEach(function (key) {
    var m = totals[key] || { total: 0, covered: 0, pct: 0 };
    var tile = covEl('div', 'cov-kpi');
    tile.appendChild(covEl('div', 'cov-kpi-value ' + covCls(m.pct), m.pct + '%'));
    tile.appendChild(covEl('div', 'cov-kpi-label', key.charAt(0).toUpperCase() + key.slice(1)));
    tile.appendChild(covEl('div', 'cov-kpi-sub', covNum(m.covered) + ' / ' + covNum(m.total)));
    var bar = covEl('div', 'cov-bar');
    var fill = covEl('div', 'cov-bar-fill bg-' + covCls(m.pct));
    fill.style.width = (m.total > 0 ? m.pct : 0) + '%';
    bar.appendChild(fill);
    tile.appendChild(bar);
    wrap.appendChild(tile);
  });
}

function covRenderRoots(roots) {
  var card = document.getElementById('cov-roots-card');
  if (!roots || roots.length <= 1) { card.hidden = true; return; }
  card.hidden = false;
  var body = document.getElementById('cov-roots');
  body.innerHTML = '';
  var table = covEl('table', 'cov-table');
  var head = covEl('tr');
  ['Package', 'Lines', 'Statements', 'Functions', 'Branches', 'Source'].forEach(function (h, i) {
    head.appendChild(covEl('th', i === 0 ? 'cov-name' : null, h));
  });
  table.appendChild(covEl('thead')).appendChild(head);
  var tbody = covEl('tbody');
  roots.forEach(function (r) {
    var tr = covEl('tr');
    tr.appendChild(covEl('td', 'cov-name', r.path));
    if (!r.available) {
      var td = covEl('td', null, 'no coverage');
      td.colSpan = 5;
      td.style.textAlign = 'right';
      td.style.color = 'var(--cov-muted)';
      tr.appendChild(td);
    } else {
      ['lines', 'statements', 'functions', 'branches'].forEach(function (k) {
        tr.appendChild(covEl('td', covCls(r.totals[k].pct), r.totals[k].pct + '%'));
      });
      tr.appendChild(covEl('td', null, r.source));
    }
    tbody.appendChild(tr);
  });
  table.appendChild(tbody);
  body.appendChild(table);
}

function covRenderFiles(files) {
  var body = document.getElementById('cov-files');
  body.innerHTML = '';
  var rows = Object.keys(files || {}).map(function (p) { return { path: p, m: files[p] }; });
  if (!rows.length) { body.appendChild(covEl('div', 'cov-empty', 'No per-file data.')); return; }
  rows.sort(function (a, b) { return a.m.lines.pct - b.m.lines.pct; });

  var table = covEl('table', 'cov-table');
  var head = covEl('tr');
  ['File', 'Lines', 'Statements', 'Functions', 'Branches'].forEach(function (h, i) {
    head.appendChild(covEl('th', i === 0 ? 'cov-name' : null, h));
  });
  table.appendChild(covEl('thead')).appendChild(head);
  var tbody = covEl('tbody');
  rows.forEach(function (r) {
    var tr = covEl('tr');
    tr.appendChild(covEl('td', 'cov-name', r.path));
    ['lines', 'statements', 'functions', 'branches'].forEach(function (k) {
      var m = r.m[k] || { pct: 0, total: 0 };
      tr.appendChild(covEl('td', m.total > 0 ? covCls(m.pct) : null, m.total > 0 ? m.pct + '%' : '—'));
    });
    tbody.appendChild(tr);
  });
  table.appendChild(tbody);
  body.appendChild(table);
}

function covRender(d) {
  var content = document.getElementById('cov-content');
  var empty = document.getElementById('cov-empty');
  if (!d.available) {
    content.hidden = true; empty.hidden = false;
    return;
  }
  content.hidden = false; empty.hidden = true;

  var lines = d.totals.lines;
  var hero = document.getElementById('cov-hero-value');
  hero.textContent = lines.pct + '%';
  hero.className = 'cov-hero-value ' + covCls(lines.pct);
  document.getElementById('cov-hero-sub').textContent =
    covNum(lines.covered) + ' of ' + covNum(lines.total) + ' lines covered';

  covRenderKpis(d.totals);
  covRenderRoots(d.roots);
  covRenderFiles(d.files);

  var age = d.ageDays === null ? '' : ' · ' + d.ageDays + 'd old';
  var status = document.getElementById('cov-status');
  status.textContent = 'From ' + d.source + age;
  var staleEl = document.getElementById('cov-stale');
  staleEl.hidden = !d.stale;
}

var covLoadingEl = document.getElementById('cov-loading');
var covErrorEl = document.getElementById('cov-error');
var covWrapEl = document.getElementById('cov-content-wrap');

function covLoad() {
  fetch(COV_DATA_URL, { cache: 'no-store' })
    .then(function (res) { if (!res.ok) throw new Error('HTTP ' + res.status); return res.json(); })
    .then(function (d) {
      covLoadingEl.hidden = true; covErrorEl.hidden = true; covWrapEl.hidden = false;
      covRender(d);
    })
    .catch(function (err) {
      covLoadingEl.hidden = true; covWrapEl.hidden = true;
      covErrorEl.hidden = false;
      covErrorEl.textContent = 'Could not load coverage: ' + err.message;
    });
}

document.getElementById('cov-refresh').addEventListener('click', covLoad);
covLoad();
`;

