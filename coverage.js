// @ts-nocheck -- vendored drop-in; not authored against any consumer's strict/checkJs config.
/**
 * @fileoverview Zero-dependency test-coverage reporter for Node.js ESM apps, plus
 * the shared `/coverage` endpoint contract for the process-mgr fleet. Sibling of
 * sloc.js — same shape, same adapters (Express or SvelteKit/Fetch), same
 * config-discovery rules.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY A COMMITTED SNAPSHOT
 * ─────────────────────────────────────────────────────────────────────────────
 * Coverage only exists after tests run — and production deploys never run tests
 * (process-mgr's update does `install` + `build` only). So a `/coverage` endpoint
 * that reads `coverage/` alone reports "no data" in prod, forever.
 *
 * The fix: when you run coverage locally, a small `.coverage-snapshot.json` is
 * written next to your package and COMMITTED. It ships with the code and is what
 * prod serves. `coverage/` itself stays gitignored.
 *
 *   "test:coverage":     "<see RECIPES below>",
 *   "posttest:coverage": "node coverage.js --snapshot"
 *
 * The endpoint reads all three sources and uses whichever was generated most
 * recently, so your dev box shows live numbers and prod shows the snapshot:
 *
 *   1. coverage/coverage-summary.json   Istanbul json-summary (vitest, jest)
 *   2. coverage/lcov.info               lcov (node:test, and any runner's lcov)
 *   3. .coverage-snapshot.json          the committed snapshot (prod)
 *
 * Note (3) is compared by its recorded `generatedAt`, NOT its file mtime — a git
 * checkout rewrites mtimes and would otherwise make old coverage look brand new.
 *
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * SETUP
 * ─────────────────────────────────────────────────────────────────────────────
 * Copy this file to the project root, add the two npm scripts, wire two routes,
 * run coverage once, and commit the generated `.coverage-snapshot.json`.
 *
 * Express:
 *   import { createCoverageRoute, createCoverageDashboardRoute } from './coverage.js'
 *   app.get('/coverage',           createCoverageRoute(process.cwd(), { name: 'my-app' }))
 *   app.get('/coverage/dashboard', createCoverageDashboardRoute({ name: 'my-app' }))
 *
 * SvelteKit (one `+server.js` per route; adjust the relative depth):
 *   // src/routes/coverage/+server.js
 *   import { createCoverageHandler } from '../../../coverage.js'
 *   export const GET = createCoverageHandler(process.cwd(), { name: 'my-app' })
 *
 *   // src/routes/coverage/dashboard/+server.js
 *   import { createCoverageDashboardHandler } from '../../../../coverage.js'
 *   export const GET = createCoverageDashboardHandler({ name: 'my-app' })
 *
 * Mount `/coverage` ABOVE any catch-all / 404 / SPA fallback, exactly as with
 * `/sloc` — a wildcard registered first will silently shadow it.
 *
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * RECIPES — making your runner emit an artifact
 * ─────────────────────────────────────────────────────────────────────────────
 * node:test (no new dependencies — emits lcov natively). It will NOT create the
 * destination directory, hence the `pretest` hook (portable: no shell mkdir -p):
 *   "pretest:coverage":  "node coverage.js --ensure-dir",
 *   "test:coverage": "node --test --experimental-test-coverage
 *                     --test-reporter=lcov --test-reporter-destination=coverage/lcov.info
 *                     --test-reporter=spec --test-reporter-destination=stdout
 *                     src/tests/*.test.js",
 *   "posttest:coverage": "node coverage.js --snapshot"
 *
 * vitest — add 'json-summary' to the coverage reporter (needs @vitest/coverage-v8
 * or @vitest/coverage-istanbul):
 *   coverage: { provider: 'v8', reporter: ['text', 'html', 'json-summary'] }
 *   "test:coverage": "vitest run --coverage",
 *   "posttest:coverage": "node coverage.js --snapshot"
 *
 * jest:
 *   coverageReporters: ['text', 'lcov', 'json-summary']
 *   "posttest:coverage": "node coverage.js --snapshot"
 *
 * Then: `npm run test:coverage` && `git add .coverage-snapshot.json`.
 *
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * MULTI-PACKAGE REPOS — coverage.config.json
 * ─────────────────────────────────────────────────────────────────────────────
 * A repo whose tests live in several packages declares them, exactly like
 * sloc.config.json. Discovery walks UP from the dir being read and stops at the
 * repo boundary (the first dir containing .git), so any sub-server's `/coverage`
 * reports the WHOLE project.
 *
 *   // media-server/coverage.config.json
 *   { "roots": ["index-server", "cache-server", "svelte-ui", "audit-server"] }
 *
 * Each root keeps its own `coverage/` and its own `.coverage-snapshot.json`
 * (generated by that package's own posttest hook). Roots with no artifact report
 * `available:false` and are EXCLUDED from the weighted project total rather than
 * counted as 0% — a package with no tests shouldn't drag the number down; it
 * shows up as a gap instead. Single-package repos need no config.
 *
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * RESPONSE SHAPE — GET /coverage
 * ─────────────────────────────────────────────────────────────────────────────
 *   {
 *     "name": "my-app",
 *     "root": "/abs/project/root",   // the config's dir, or rootDir — dedupe key
 *     "available": true,
 *     "source": "snapshot",          // coverage-summary | lcov | snapshot | mixed
 *     "generatedAt": "2026-07-09T…", // OLDEST root's timestamp (honest staleness)
 *     "ageDays": 3.2,
 *     "stale": false,                // ageDays > staleAfterDays (default 14)
 *     "totals": {
 *       "lines":      { "total": 1620, "covered": 518, "pct": 31.97 },
 *       "statements": { … }, "functions": { … }, "branches": { … }
 *     },
 *     "roots": [ { "path": "index-server", "available": true, "source": "…",
 *                  "generatedAt": "…", "totals": { … } } ]
 *   }
 *
 * Project totals are WEIGHTED (Σcovered / Σtotal across roots), never a mean of
 * percentages. `?detail=true` additionally returns `files` — a map of
 * project-relative path → per-metric counts. It's opt-in because it's large and
 * process-mgr's fleet aggregator never needs it.
 *
 * An app that can't use this script just needs to return this JSON shape.
 *
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * LIMITATIONS
 * ─────────────────────────────────────────────────────────────────────────────
 * - lcov carries no `statements` metric. When reading lcov, `statements` is
 *   aliased to `lines`. Don't read across-runner statement deltas as meaningful.
 * - v8 and istanbul providers legitimately disagree on the same code. Percentages
 *   are comparable for one app over time, not strictly between apps.
 * - node:test's --experimental-test-coverage only reports files it actually
 *   LOADED during the run. A module no test ever imports is invisible, not 0% —
 *   so these percentages read optimistically high. Runners configured with an
 *   `include` glob (vitest/jest) count untested files as 0% and read lower.
 * - A failing suite exits non-zero, so npm skips `posttest:coverage` and no
 *   snapshot is written. That's deliberate: never publish coverage from a red run.
 * - `generatedAt` for a multi-root project is the OLDEST root's timestamp, so the
 *   number is never presented as fresher than its stalest part.
 * - Nothing here runs your tests. `createCoverageRunRoute` exists but is NOT
 *   wired by default and must never be exposed in production.
 */

import { readFile, writeFile, stat, readdir, mkdir } from 'node:fs/promises';
import { join, dirname, resolve, relative, sep, isAbsolute } from 'node:path';

const METRICS = ['lines', 'statements', 'functions', 'branches'];

export const SNAPSHOT_FILE = '.coverage-snapshot.json';
export const CONFIG_FILE = 'coverage.config.json';
export const DEFAULT_STALE_AFTER_DAYS = 14;

// ── Metric helpers ───────────────────────────────────────────────────────────

function pct(covered, total) {
    return total > 0 ? Math.round((covered / total) * 10000) / 100 : 0;
}

function emptyMetric() { return { total: 0, covered: 0, pct: 0 }; }

function emptyTotals() {
    const t = {};
    for (const m of METRICS) t[m] = emptyMetric();
    return t;
}

function normMetric(m) {
    const total = Number(m?.total) || 0;
    const covered = Number(m?.covered) || 0;
    return { total, covered, pct: pct(covered, total) };
}

function normTotals(t) {
    const out = emptyTotals();
    for (const m of METRICS) out[m] = normMetric(t?.[m]);
    return out;
}

function finalize(totals) {
    for (const m of METRICS) totals[m].pct = pct(totals[m].covered, totals[m].total);
    return totals;
}

/** Weighted accumulate: sums counts, never averages percentages. */
function addTotals(dst, src) {
    for (const m of METRICS) {
        dst[m].total += src?.[m]?.total ?? 0;
        dst[m].covered += src?.[m]?.covered ?? 0;
    }
    return dst;
}

// ── Path helpers ─────────────────────────────────────────────────────────────

function toPosix(p) { return String(p).split(sep).join('/').replace(/\\/g, '/'); }

/**
 * Istanbul summaries key files by ABSOLUTE authoring-machine paths
 * ("C:/dev/app/src/x.ts"). Store them project-relative so prod doesn't serve dev
 * paths and snapshot diffs stay stable across machines.
 */
function relPath(rootDir, filePath) {
    const p = toPosix(filePath);
    if (isAbsolute(p) || /^[A-Za-z]:\//.test(p)) {
        const r = relative(rootDir, p.replace(/\//g, sep));
        if (r && !r.startsWith('..')) return toPosix(r);
    }
    return p.replace(/^\.\//, '');
}

// ── Artifact parsers ─────────────────────────────────────────────────────────

/** Istanbul `coverage-summary.json`: { total: {...}, "<abs file>": {...} }. */
function fromIstanbulSummary(rootDir, data) {
    const totals = normTotals(data?.total);
    const files = {};
    for (const [key, value] of Object.entries(data ?? {})) {
        if (key === 'total' || !value || typeof value !== 'object' || !value.lines) continue;
        files[relPath(rootDir, key)] = normTotals(value);
    }
    return { totals, files };
}

/**
 * lcov: per-record LF/LH (lines), FNF/FNH (functions), BRF/BRH (branches).
 * There is no statements metric — it's aliased to lines.
 */
function fromLcov(rootDir, text) {
    const totals = emptyTotals();
    const files = {};
    let current = null;

    const flush = () => {
        if (!current) return;
        current.metrics.statements = { ...current.metrics.lines }; // lcov has no statements
        finalize(current.metrics);
        files[current.path] = current.metrics;
        addTotals(totals, current.metrics);
        current = null;
    };

    for (const raw of String(text).split('\n')) {
        const line = raw.trim();
        if (!line) continue;

        if (line.startsWith('SF:')) {
            flush();
            current = { path: relPath(rootDir, line.slice(3)), metrics: emptyTotals() };
            continue;
        }
        if (!current) continue;
        if (line === 'end_of_record') { flush(); continue; }

        const idx = line.indexOf(':');
        if (idx === -1) continue;
        const key = line.slice(0, idx);
        const num = Number(line.slice(idx + 1));
        if (!Number.isFinite(num)) continue;

        switch (key) {
            case 'LF':  current.metrics.lines.total = num; break;
            case 'LH':  current.metrics.lines.covered = num; break;
            case 'FNF': current.metrics.functions.total = num; break;
            case 'FNH': current.metrics.functions.covered = num; break;
            case 'BRF': current.metrics.branches.total = num; break;
            case 'BRH': current.metrics.branches.covered = num; break;
            default: break;
        }
    }
    flush();
    return { totals: finalize(totals), files };
}

// ── Artifact discovery (one package root) ────────────────────────────────────

async function readCandidate(rootDir, source, file) {
    let raw, st;
    try {
        st = await stat(file);
        raw = await readFile(file, 'utf-8');
    } catch {
        return null;
    }

    try {
        if (source === 'lcov') {
            const { totals, files } = fromLcov(rootDir, raw);
            if (totals.lines.total === 0) return null;
            return { source, generatedAt: new Date(st.mtimeMs).toISOString(), ts: st.mtimeMs, totals, files };
        }

        const data = JSON.parse(raw);

        if (source === 'coverage-summary') {
            const { totals, files } = fromIstanbulSummary(rootDir, data);
            return { source, generatedAt: new Date(st.mtimeMs).toISOString(), ts: st.mtimeMs, totals, files };
        }

        // snapshot: trust its recorded generatedAt — a git checkout rewrites mtime.
        const generatedAt = data?.generatedAt ?? new Date(st.mtimeMs).toISOString();
        const ts = Date.parse(generatedAt);
        return {
            source: 'snapshot',
            generatedAt,
            ts: Number.isFinite(ts) ? ts : st.mtimeMs,
            totals: finalize(normTotals(data?.totals)),
            files: data?.files ?? {},
        };
    } catch {
        return null; // malformed artifact — treat as absent rather than 500
    }
}

/** Read one package root, preferring whichever artifact was generated most recently. */
export async function readRootCoverage(rootDir) {
    const dir = resolve(rootDir);
    const found = (await Promise.all([
        readCandidate(dir, 'coverage-summary', join(dir, 'coverage', 'coverage-summary.json')),
        readCandidate(dir, 'lcov', join(dir, 'coverage', 'lcov.info')),
        readCandidate(dir, 'snapshot', join(dir, SNAPSHOT_FILE)),
    ])).filter(Boolean);

    if (!found.length) return null;
    found.sort((a, b) => b.ts - a.ts);
    return found[0];
}

// ── Config discovery (mirrors sloc.js) ───────────────────────────────────────

async function isRepoRoot(dir) {
    try { await readdir(join(dir, '.git')); return true; } catch { /* not a dir */ }
    try { await readFile(join(dir, '.git'), 'utf-8'); return true; } catch { /* not a gitlink */ }
    return false;
}

async function findCoverageConfig(startDir) {
    let dir = resolve(startDir);
    for (;;) {
        try {
            const data = JSON.parse(await readFile(join(dir, CONFIG_FILE), 'utf-8'));
            if (data && Array.isArray(data.roots)) return { dir, config: data };
        } catch { /* keep looking */ }

        if (await isRepoRoot(dir)) return null; // don't escape the repo
        const parent = dirname(dir);
        if (parent === dir) return null;
        dir = parent;
    }
}

// ── Public API ───────────────────────────────────────────────────────────────

/**
 * Read coverage for the project containing `rootDir`. If a coverage.config.json
 * is found at/above it (within the repo), every declared root is read and the
 * totals are weighted across the roots that have data.
 * @returns {Promise<object>} See RESPONSE SHAPE above.
 */
export async function readCoverage(rootDir, options = {}) {
    const { detail = false, staleAfterDays = DEFAULT_STALE_AFTER_DAYS, useConfig = true } = options;

    const found = useConfig ? await findCoverageConfig(rootDir) : null;
    const base = found ? found.dir : resolve(rootDir);
    const rootSpecs = found
        ? found.config.roots.map((r) => (typeof r === 'string' ? { path: r } : r))
        : [{ path: '.' }];

    const roots = [];
    const totals = emptyTotals();
    const files = {};
    let oldestTs = Infinity;
    const sources = new Set();

    for (const spec of rootSpecs) {
        const dir = join(base, spec.path);
        const report = await readRootCoverage(dir);
        const prefix = (spec.path === '.' || spec.path === '') ? '' : toPosix(spec.path).replace(/\/+$/, '');

        if (!report) {
            roots.push({ path: prefix || '.', available: false, source: null, generatedAt: null, totals: null });
            continue;
        }

        roots.push({
            path: prefix || '.',
            available: true,
            source: report.source,
            generatedAt: report.generatedAt,
            totals: report.totals,
        });

        addTotals(totals, report.totals);
        sources.add(report.source);
        if (report.ts < oldestTs) oldestTs = report.ts;

        if (detail) {
            for (const [p, m] of Object.entries(report.files)) {
                files[prefix ? `${prefix}/${p}` : p] = m;
            }
        }
    }

    const available = roots.some((r) => r.available);
    if (!available) {
        return {
            root: base, available: false, source: null, generatedAt: null,
            ageDays: null, stale: false, totals: emptyTotals(),
            roots, ...(detail ? { files: {} } : {}),
        };
    }

    const ageDays = Math.round(((Date.now() - oldestTs) / 86400000) * 10) / 10;

    return {
        root: base,
        available: true,
        source: sources.size === 1 ? [...sources][0] : 'mixed',
        generatedAt: new Date(oldestTs).toISOString(),
        ageDays,
        stale: ageDays > staleAfterDays,
        totals: finalize(totals),
        roots,
        ...(detail ? { files } : {}),
    };
}

/**
 * Write `.coverage-snapshot.json` for a single package from its LIVE artifact
 * (coverage-summary.json or lcov.info). Never reads an existing snapshot — that
 * would let a stale snapshot perpetuate itself.
 * @returns {Promise<{file: string, source: string, totals: object, fileCount: number}>}
 */
export async function writeSnapshot(rootDir = process.cwd()) {
    const dir = resolve(rootDir);
    const found = (await Promise.all([
        readCandidate(dir, 'coverage-summary', join(dir, 'coverage', 'coverage-summary.json')),
        readCandidate(dir, 'lcov', join(dir, 'coverage', 'lcov.info')),
    ])).filter(Boolean);

    if (!found.length) {
        throw new Error(
            `No coverage artifact in ${dir}. Expected coverage/coverage-summary.json or coverage/lcov.info — run your test:coverage script first.`
        );
    }
    found.sort((a, b) => b.ts - a.ts);
    const best = found[0];

    // Sort paths so the committed file has stable, reviewable diffs.
    const files = {};
    for (const p of Object.keys(best.files).sort()) files[p] = best.files[p];

    const file = join(dir, SNAPSHOT_FILE);
    const payload = {
        version: 1,
        generatedAt: best.generatedAt,
        source: best.source,
        totals: best.totals,
        files,
    };
    await writeFile(file, JSON.stringify(payload, null, 2) + '\n', 'utf-8');
    return { file, source: best.source, totals: best.totals, fileCount: Object.keys(files).length };
}

// ── Endpoint adapters ────────────────────────────────────────────────────────

// Shared cache/compute core behind the Express and Fetch adapters, so /coverage
// behaves identically (same 30s cache) whichever framework wired it up.
function createReportProvider(rootDir, options = {}) {
    const { cacheMs = 30000, name, ...readOptions } = options;
    let cache = null;
    let cachedAt = 0;

    return async function getReport(detail) {
        const now = Date.now();
        if (!detail && cache && now - cachedAt < cacheMs) return cache;

        const report = await readCoverage(rootDir, { ...readOptions, detail });
        const payload = name ? { name, ...report } : report;

        if (!detail) { cache = payload; cachedAt = now; }
        return payload;
    };
}

function wantsDetail(value) { return value === 'true' || value === '1'; }

/** Express handler for `GET /coverage`. */
export function createCoverageRoute(rootDir, options = {}) {
    const getReport = createReportProvider(rootDir, options);
    return async function coverageHandler(req, res) {
        try {
            res.json(await getReport(wantsDetail(req.query?.detail)));
        } catch (err) {
            res.status(500).json({ error: err.message });
        }
    };
}

/** Fetch/SvelteKit handler for `GET /coverage`. */
export function createCoverageHandler(rootDir, options = {}) {
    const getReport = createReportProvider(rootDir, options);
    return async function coverageRequestHandler(event) {
        try {
            const payload = await getReport(wantsDetail(event?.url?.searchParams?.get('detail')));
            return new Response(JSON.stringify(payload), { headers: { 'content-type': 'application/json' } });
        } catch (err) {
            return new Response(JSON.stringify({ error: err.message }), {
                status: 500, headers: { 'content-type': 'application/json' },
            });
        }
    };
}

/**
 * OPTIONAL, not wired by default: spawns `npm run test:coverage`. Running a test
 * suite inside a live server is a production hazard (CPU, real data, external
 * services) — only mount this behind an explicit dev/admin guard.
 */
export function createCoverageRunRoute(options = {}) {
    const { cwd = process.cwd(), script = 'test:coverage' } = options;
    let running = false;

    return async function coverageRunHandler(req, res) {
        if (running) { res.status(409).json({ error: 'Tests already running' }); return; }
        running = true;
        res.status(202).json({ started: true });

        const { spawn } = await import('node:child_process');
        const child = spawn('npm', ['run', script], { cwd, shell: true, stdio: 'inherit' });
        child.on('close', () => { running = false; });
        child.on('error', () => { running = false; });
    };
}

